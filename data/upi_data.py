def load_upi_data() -> pd.DataFrame:
    """
    Load monthly UPI transaction data.

    Returns
    -------
    pd.DataFrame
        Index: DatetimeIndex (monthly, MS freq)
        Columns: transactions_mn (millions), amount_bn_inr (billion INR)
    """
    df = pd.read_csv(StringIO(_UPI_CSV.strip()), parse_dates=["date"])
    df = df.set_index("date")
    df.index = pd.DatetimeIndex(df.index, freq="MS")
    df = df.sort_index()
    # Remove the early-adopter ramp-up (pre-demonetisation noise, Apr–Sep 2016)
    df = df[df.index >= "2017-01-01"].copy()
    return df


def get_log_series(df: pd.DataFrame, col: str = "transactions_mn") -> pd.Series:
    """Return log-transformed series for variance stabilisation."""
    return np.log(df[col])


